// 判断一个大数能否被9整除

#include <stdio.h>
int main()
{
    const char *u = "4597707459413295369168607024407034079280631601419740994722759979114987668308624680329889963962250959"; // 超长数字串的处理（不过考虑到题目的特殊性，一般长数字串会考虑用结构体来接住？

    int sum = 0;
    int i = 0;

    while (u[i] != '\0')
    {
        sum += u[i] - '0'; // 隐式转换！
        i++;
    }
    if (sum % 9 == 0)
    {
        printf("Yes");
    }
    else
        printf("No");

    return 0;
}